package uk.co.kilfeder.damask.podcasts

import androidx.compose.ui.graphics.painter.BitmapPainter
import androidx.compose.ui.graphics.toComposeImageBitmap
import androidx.compose.ui.window.Window
import androidx.compose.ui.window.application
import org.jetbrains.skia.Image
import uk.co.kilfeder.damask.podcasts.presentation.app.AppGraph
import uk.co.kilfeder.damask.podcasts.presentation.app.create
import uk.co.kilfeder.damask.podcasts.ui.App

fun main() {
    val graph = AppGraph.create()
    val icon = loadIcon()
    application {
        Window(onCloseRequest = ::exitApplication, title = "Damask", icon = icon) {
            App(graph)
        }
    }
}

/** The window and taskbar icon (generated by branding/icon/generate.py). */
private fun loadIcon(): BitmapPainter? {
    val bytes = Thread.currentThread().contextClassLoader
        ?.getResourceAsStream("damask-icon.png")
        ?.use { it.readBytes() }
        ?: return null
    return BitmapPainter(Image.makeFromEncoded(bytes).toComposeImageBitmap())
}
